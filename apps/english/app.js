  /* ---------------- review queue ---------------- */
  async function reviewView() {
    const st = Store.get(), due = C.dueCards(st);
    const total = Object.values(st.review.cards).filter((x) => !x.mastered).length;
    if (!due.length) {
      main.replaceChildren(h("section.wrap.narrow", h("p.kicker", "Review · Repaso"), h("h1", "Nothing to review right now"),
        h("p", total ? `${total} item${total === 1 ? "" : "s"} will come back later, spaced out so you remember them.` : "Items you miss in lessons will appear here."),
        h("p.muted", { lang: "es" }, "Lo que falles en las lecciones aparece aquí, espaciado en el tiempo para que lo recuerdes."), h("a.btn", { href: "#/" }, "Dashboard")));
      return;
    }
    const card = due[0];
    const box = h("div.act");
    const answer = (knew) => { Store.update((s) => C.reviewAnswer(s, card.id, knew)); reviewView(); };
    if (card.kind === "phrase") {
      const back = h("div", { hidden: true }, card.es ? h("p", { lang: "es" }, card.es) : null, h("div.row",
        h("button.btn.btn--primary", { type: "button", onclick: () => answer(true) }, "I knew it · Lo sabía"), h("button.btn", { type: "button", onclick: () => answer(false) }, "Not yet · Todavía no")));
      box.append(h("p.q__prompt", card.es ? "Do you know what this means? Say it out loud first." : "Say this sentence out loud, then check yourself."),
        h("p.model", h("b", card.en), " ", window.CPEUI.sayBtn(card.en)), h("button.btn", { type: "button", onclick: (e) => { e.currentTarget.remove(); back.hidden = false; } }, "Show answer"), back);
    } else {
      const L = await lessonData(card.lesson);
      let item = null;
      L.sections.forEach((s) => s.activities.forEach((a) => { if (a.id === card.act) item = a; }));
      if (item && card.q) item = Object.assign({}, (item.questions || item.items).find((q) => q.id === card.q), { clip: item.clip || (item.items || []).find((q) => q.id === card.q)?.clip });
      const done = h("div");
      if (!item) { Store.update((s) => { delete s.review.cards[card.id]; }); return reviewView(); }
      const ctx = { lesson: L, clips: L.clips, level: levelNow(), seed: Date.now(), record: () => {}, review: () => {}, saveSpeaking: () => {}, mastery: () => {}, next: () => reviewView() };
      if (item.type === "order") {
        const el = window.CPEAct.render(item, Object.assign({}, ctx, { record: (o) => Store.update((s) => C.reviewAnswer(s, card.id, o.correct)), next: () => reviewView() }));
        box.append(el);
      } else {
        box.append(window.CPEAct.choiceQ(item, ctx, (ok) => { Store.update((s) => C.reviewAnswer(s, card.id, ok)); done.replaceChildren(h("button.btn.btn--primary", { type: "button", onclick: () => reviewView() }, due.length > 1 ? "Next →" : "Done")); }), done);
      }
    }
    main.replaceChildren(h("section.wrap.narrow", h("p.kicker", `Review · ${due.length} due`), h("p.muted.small", card.title || ""), box));
  }

