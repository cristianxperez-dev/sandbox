  /* ---------------- review queue ---------------- */
  async function reviewView() {
    const l = Store.learner(), due = C.dueCards(l);
    const total = Object.values(l.review.cards).filter((x) => !x.mastered).length;
    if (!due.length) {
      main.replaceChildren(h("section.wrap.narrow", h("p.kicker", nativeText("Review", "Repaso")), h("h1", L("Nothing to review right now", "Nada que repasar ahora")),
        h("p", total ? L(`${total} item${total === 1 ? "" : "s"} will come back later, spaced out so you remember them.`, `${total} volverán más adelante.`) : L("Items you miss in lessons will appear here.", "Lo que falles en las lecciones aparece aquí.")),
        h("a.btn", { href: "#/" }, "Home")));
      return;
    }
    const card = due[0];
    const box = h("div.act");
    const answer = (knew) => { Store.updateLearner((y) => C.reviewAnswer(y, card.id, knew)); reviewView(); };
    if (card.kind === "phrase") {
      const text = card.text || card.en, tr = card.tr != null ? card.tr : card.es, lang = card.lang || "en";
      viewCtx = { target: lang, native: C.otherLang(lang), specialty: l.profile.specialty, level: "A1" };
      const back = h("div", { hidden: true }, tr ? h("p", { lang: C.otherLang(lang) }, tr) : null, h("div.row",
        h("button.btn.btn--primary", { type: "button", onclick: () => answer(true) }, "I knew it"), h("button.btn", { type: "button", onclick: () => answer(false) }, "Not yet")));
      box.append(h("p.q__prompt", tr ? L("Do you know what this means? Say it out loud first.", "¿Sabes qué significa? Dilo en voz alta primero.") : L("Say this sentence out loud, then check yourself.", "Di esta oración en voz alta.")),
        h("p.model", h("b", { lang }, text), " ", U.sayBtn(text, lang)), h("button.btn", { type: "button", onclick: (e) => { e.currentTarget.remove(); back.hidden = false; } }, "Show answer"), back);
    } else {
      const Ld = await lessonData(card.lesson).catch(() => null);
      let item = null;
      if (Ld) Ld.sections.forEach((s) => s.activities.forEach((a) => { if (a.id === card.act) item = a; }));
      if (item && card.q) item = Object.assign({}, (item.questions || item.items).find((q) => q.id === card.q), { clip: item.clip || ((item.items || []).find((q) => q.id === card.q) || {}).clip });
      if (!item) { Store.updateLearner((y) => { delete y.review.cards[card.id]; }); return reviewView(); }
      viewCtx = { target: Ld.target, native: Ld.native, specialty: l.profile.specialty, level: "A1" };
      const done = h("div");
      const ctx = { lesson: Ld, clips: Ld.clips, level: "A1", seed: Date.now(), record: () => {}, review: () => {}, saveSpeaking: () => {}, mastery: () => {}, next: () => reviewView() };
      if (item.type === "order") box.append(window.CPEAct.render(item, Object.assign({}, ctx, { record: (o) => Store.updateLearner((y) => C.reviewAnswer(y, card.id, o.correct)), next: () => reviewView() })));
      else box.append(window.CPEAct.choiceQ(item, ctx, (ok) => { Store.updateLearner((y) => C.reviewAnswer(y, card.id, ok)); done.replaceChildren(h("button.btn.btn--primary", { type: "button", onclick: () => reviewView() }, due.length > 1 ? "Next →" : "Done")); }), done);
    }
    main.replaceChildren(h("section.wrap.narrow", h("p.kicker", `Review · ${due.length} due`), h("p.muted.small", card.title || ""), box));
  }

