/* Baseball Feud 2.0 — choose the game everyone sees by default.
     node apps/baseball-feud-2/games/make-default.mjs games/<file>.json [game-id]
   Writes games/default-game.js from a game exported with EXPORT GAME (kept unchanged next to it).
   The page reads window.BF2_DEFAULT_GAME; this file is the one place the default is chosen. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, basename, relative } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url)), app = dirname(here);
const src = process.argv[2] || "games/sample-game-volume-1.json";
const file = join(app, src);
const data = JSON.parse(readFileSync(file, "utf8"));
if (data.app !== "baseball-feud-2" || !Array.isArray(data.plays) || !data.plays.length) throw new Error("not a Baseball Feud 2.0 game export with plays");
const id = process.argv[3] || "g-" + basename(file, ".json").toLowerCase().replace(/[^a-z0-9]+/g, "-");
const out = `/* Baseball Feud 2.0 — the default game (generated by games/make-default.mjs from ${relative(app, file)}; don't edit by hand).
   Shown to every visitor at the start of a session; their own games stay in GAMES. */
window.BF2_DEFAULT_GAME = ${JSON.stringify({ id, file: relative(app, file), data }, null, 1)};
`;
writeFileSync(join(here, "default-game.js"), out);
console.log(`default game: ${id} — “${data.sessionName}”, ${data.plays.length} plays → games/default-game.js`);
